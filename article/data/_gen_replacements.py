# Multi-needle quality (Pass E) — augments long-context quality
# ============================================================
def multineedle_table():
    res = NEEDLE.get("results", {})
    out = [
r"\begin{table}[t]",
r"\caption{Multi-needle long-context retrieval (W2.B).  Five fixed-content",
r"codes planted at depths 10\,/\,30\,/\,50\,/\,70\,/\,90\,\% of a filler",
r"document; model is asked to enumerate them.  Score = number of codes",
r"correctly recovered (median across 2 runs).  Verified-stock 24-CU,",
r"Ollama~0.20.0/llama.cpp~b9265, KV~q4\_0.}\label{tab:multineedle}",
r"\centering",
r"\scriptsize",
r"\begin{tabular}{@{}lccccc@{}}",
r"\toprule",
r"\textbf{Model} & \textbf{16K} & \textbf{32K} & \textbf{64K} & \textbf{128K} & \textbf{Notes} \\",
r"\otoprule",
    ]
    rendered = 0
    for name, m in res.items():
        tiers = m.get("tiers", {})
        cells = []
        notes = []
        for ctx in (16384, 32768, 65536, 131072):
            t = tiers.get(str(ctx), {})
            agg = t.get("aggregate", {})
            sm = agg.get("needle_score_median")
            ladder = t.get("ladder_status", "")
            if sm is None and ladder == "capped":
                cells.append("cap.")
            elif sm is None and ladder in ("vm_skip", "stopped"):
                cells.append("---")
            elif sm is None:
                cells.append("---")
            else:
                cells.append(f"{int(sm)}/5")
        out.append(f"{latex_name(name)} & " + " & ".join(cells) + f" & {' '.join(notes)} \\\\")
        rendered += 1
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    if rendered == 0:
        return
    write("_table_multineedle.tex", "\n".join(out) + "\n")


