# Table 8 — Cold Start latency (Pass D cold step has full data)
# ============================================================
def get_cold(name):
    if name not in COLD: return None
    m = COLD[name]
    runs = m.get("cold_runs") or m.get("runs", [])
    cold = [r for r in runs if r.get("status") == "ok"]
    if not cold:
        return None
    times = [r.get("wall_s") for r in cold if r.get("wall_s")]
    loads = [r.get("load_ms",0)/1000 for r in cold if r.get("load_ms")]
    return {"times": times, "loads": loads, "med_s": m.get("cold_med_s"),
            "warm_s": m.get("warm_s")}

def table_cold():
    rows = [
        ("qwen3.5-35b-a3b",  "qwen3-5-35b-a3b-iq2m-ollama"),
        ("qwen3.5:9b",       "qwen3.5-9b-ollama"),
    ]
    out = [
r"\begin{table}[t]",
r"\caption{Cold-start TTFT: model fully unloaded $\to$ first generated",
r"token.  Three runs per model on verified-stock 24-CU,",
r"Ollama~0.20.0.}\label{tab:cold_start}",
r"\centering",
r"\scriptsize",
r"\begin{tabular}{@{}lccccc@{}}",
r"\toprule",
r"\textbf{Model} & \textbf{Run~1} & \textbf{Run~2} & \textbf{Run~3} & \textbf{Med.} & \textbf{Load} \\",
r"\otoprule",
    ]
    for art, key in rows:
        c = get_cold(key)
        if c is None:
            out.append(f"{latex_name(art)} & --- & --- & --- & --- & --- \\\\")
            continue
        times = c["times"]
        loads = c["loads"]
        med = c["med_s"]
        load_med = statistics.median(loads) if loads else None
        cells = [f"{t:.1f}\\,s" for t in times[:3]]
        while len(cells) < 3:
            cells.append("---")
        med_s = f"{med:.1f}\\,s" if med is not None else "---"
        load_s = f"{load_med:.1f}\\,s" if load_med is not None else "---"
        out.append(f"{latex_name(art)} & " + " & ".join(cells) + f" & {med_s} & {load_s} \\\\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    write("_table_cold_start.tex", "\n".join(out) + "\n")


