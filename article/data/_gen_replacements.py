def latex_name(name):
    return name.replace(":", r"\!:\!").replace("_", r"\_")

def fmt_qual(q):
    return q.replace("%", "\\%")

def write(name, txt):
    p = D / name
    open(p, "w").write(txt)
    print(f"  wrote {p}")

def table1():
    out = [
r"\begin{table}[ht]",
r"\caption{Generation speed and VRAM for representative models at 4K",
r"context. $\star$~recommended.  All numbers from the verified-stock",
r"24-CU configuration under Ollama 0.20.0.  This table supersedes the",
r"original Ollama-0.18.0 numbers, which were measured before a kernel",
r"upgrade and accompanying CU-unlock event went undetected on the",
r"benchmark host; see Section~\ref{subsec:errata}.}\label{tab:gen_speed}",
r"\centering",
r"\scriptsize",
r"\setlength{\tabcolsep}{3pt}",
r"\begin{tabular}{@{}lccrrcr@{}}",
r"\toprule",
r"\textbf{Model} & \textbf{Par.} & \textbf{Quant} & \textbf{Gen} & \textbf{Pfill} & \textbf{VRAM} & \textbf{Qual.} \\",
r" & & & \textbf{(t/s)} & \textbf{(t/s)} & \textbf{(GiB)} & \\",
r"\otoprule",
r"\multicolumn{7}{@{}l}{\scriptsize $^a$\,Qwen3.5-35B-A3B (35\,B total, 3\,B active per token), IQ2\_M $\approx$2.5\,bits/weight.} \\",
r"\addlinespace[1pt]",
    ]
    for art_name, params, quant, key, vram, qual, star in T1_ROWS:
        c = CANON.get(key)
        nm = (r"$\star$ " if star else "") + latex_name(art_name) + (r"\,$^a$" if art_name == "qwen3.5-35b-a3b" else "")
        q = quant.replace('_', r'\_')
        if c is None:
            out.append(f"{nm} & {params} & {q} & --- & --- & {vram:.1f} & {fmt_qual(qual)} \\\\")
        else:
            out.append(f"{nm} & {params} & {q} & {c['gen']:>5.1f} & {c['pp']:>5.1f} & {vram:.1f} & {fmt_qual(qual)} \\\\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    write("_table1_replacement.tex", "\n".join(out) + "\n")


