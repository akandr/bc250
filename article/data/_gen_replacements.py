def table_cu_unlock():
    out = [
r"\begin{table}[t]",
r"\caption{Throughput before and after the 40-CU unlock on the",
r"11-model paired re-run subset.  All numbers in tok/s, median of 3 runs",
r"at 4K context, prompt $\approx$262 tokens, KV~q4\_0, flash attention",
r"on, llama.cpp~b9265.  $\Delta$ columns give the multiplicative speed-up",
r"from verified-stock 24~CUs to patched 40~CUs.}\label{tab:cu_unlock}",
r"\centering",
r"\scriptsize",
r"\begin{tabular}{@{}lrrcrrc@{}}",
r"\toprule",
r"\textbf{Model} & \textbf{Gen 24} & \textbf{Gen 40} & $\boldsymbol{\Delta_\text{gen}}$",
r"               & \textbf{Pfill 24} & \textbf{Pfill 40} & $\boldsymbol{\Delta_\text{pf}}$ \\",
r"\otoprule",
    ]
    gen_ratios, pp_ratios = [], []
    for label, key in PAIRED_ROWS:
        ag = A.get(key, {}).get("aggregate", {})
        bg = B.get(key, {}).get("aggregate", {})
        ag_g = ag.get("gen_tok_s_median"); ag_p = ag.get("prefill_tok_s_median")
        bg_g = bg.get("gen_tok_s_median"); bg_p = bg.get("prefill_tok_s_median")
        if ag_g is None or bg_g is None:
            continue
        gr = bg_g / ag_g
        pr = bg_p / ag_p if (ag_p and bg_p) else None
        gen_ratios.append(gr)
        if pr: pp_ratios.append(pr)
        ag_p_s = "---" if ag_p is None else f"{ag_p:.1f}"
        bg_p_s = "---" if bg_p is None else f"{bg_p:.1f}"
        pr_s = "---" if pr is None else f"{pr:.2f}$\\times$"
        out.append(f"{label} & {ag_g:.1f} & {bg_g:.1f} & {gr:.2f}$\\times$ & "
                   f"{ag_p_s} & {bg_p_s} & {pr_s} \\\\")
    if gen_ratios:
        out.append(r"\midrule")
        out.append(f"\\textbf{{Median across set}}  &        &       & "
                   f"\\textbf{{{statistics.median(gen_ratios):.2f}$\\boldsymbol{{\\times}}$}}")
        out.append(f"                            &        &       & "
                   f"\\textbf{{{statistics.median(pp_ratios):.2f}$\\boldsymbol{{\\times}}$}} \\\\")
    out.append(r"\bottomrule")
    out.append(r"\end{tabular}")
    out.append(r"\end{table}")
    write("_table_cu_unlock.tex", "\n".join(out) + "\n")
    print(f"  CU unlock: gen median {statistics.median(gen_ratios):.3f}× pp median {statistics.median(pp_ratios):.3f}×")


